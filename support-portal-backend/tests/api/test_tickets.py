class TestTicketStateMachine:
    def _setup(self, client: TestClient, email_prefix: str):
        auth = _signup_and_login(client, f"{email_prefix}@co.com", f"{email_prefix} Org")
        token = auth["access_token"]
        customer = _create_customer(client, token)
        ticket = _create_ticket(client, token, customer["id"])
        return token, ticket

    def test_new_to_open_valid(self, client: TestClient):
        token, ticket = self._setup(client, "sm_nto")
        resp = client.post(
            f"/api/v1/tickets/{ticket['id']}/status",
            json={"status": "OPEN"},
            headers=_auth(token),
        )
        assert resp.status_code == 200
        assert resp.json()["status"] == "OPEN"

    def test_new_to_closed_invalid(self, client: TestClient):
        token, ticket = self._setup(client, "sm_ntc")
        resp = client.post(
            f"/api/v1/tickets/{ticket['id']}/status",
            json={"status": "CLOSED"},
            headers=_auth(token),
        )
        # Invalid transition — expects 422
        assert resp.status_code == 422

    def test_resolved_to_closed_valid(self, client: TestClient):
        token, ticket = self._setup(client, "sm_rtc")
        # NEW → OPEN → RESOLVED → CLOSED
        tid = ticket["id"]
        client.post(f"/api/v1/tickets/{tid}/status", json={"status": "OPEN"}, headers=_auth(token))
        client.post(f"/api/v1/tickets/{tid}/status", json={"status": "RESOLVED"}, headers=_auth(token))
        resp = client.post(
            f"/api/v1/tickets/{tid}/status", json={"status": "CLOSED"}, headers=_auth(token)
        )
        assert resp.status_code == 200
        assert resp.json()["status"] == "CLOSED"

    def test_cancelled_is_terminal(self, client: TestClient):
        token, ticket = self._setup(client, "sm_cancel")
        tid = ticket["id"]
        client.post(f"/api/v1/tickets/{tid}/status", json={"status": "CANCELLED"}, headers=_auth(token))
        resp = client.post(
            f"/api/v1/tickets/{tid}/status", json={"status": "OPEN"}, headers=_auth(token)
        )
        assert resp.status_code == 422

    def test_resolved_sets_resolved_at(self, client: TestClient):
        token, ticket = self._setup(client, "sm_rsat")
        tid = ticket["id"]
        client.post(f"/api/v1/tickets/{tid}/status", json={"status": "OPEN"}, headers=_auth(token))
        resp = client.post(
            f"/api/v1/tickets/{tid}/status", json={"status": "RESOLVED"}, headers=_auth(token)
        )
        assert resp.status_code == 200
        assert resp.json()["resolved_at"] is not None

    def test_closed_sets_closed_at(self, client: TestClient):
        token, ticket = self._setup(client, "sm_csat")
        tid = ticket["id"]
        client.post(f"/api/v1/tickets/{tid}/status", json={"status": "OPEN"}, headers=_auth(token))
        client.post(f"/api/v1/tickets/{tid}/status", json={"status": "RESOLVED"}, headers=_auth(token))
        resp = client.post(
            f"/api/v1/tickets/{tid}/status", json={"status": "CLOSED"}, headers=_auth(token)
        )
        assert resp.status_code == 200
        assert resp.json()["closed_at"] is not None


