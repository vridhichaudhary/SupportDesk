class TestBulkOperations:
    def test_bulk_assign(self, client: TestClient):
        auth = _signup_and_login(client, "t_bulk@co.com", "Bulk Org")
        token = auth["access_token"]
        customer = _create_customer(client, token, "bulk_cust@test.com")

        t1 = _create_ticket(client, token, customer["id"], "Bulk T1")
        t2 = _create_ticket(client, token, customer["id"], "Bulk T2")

        resp = client.post(
            "/api/v1/tickets/bulk/assign",
            json={
                "ticket_ids": [t1["id"], t2["id"]],
                "assigned_user_id": auth["user_id"],
            },
            headers=_auth(token),
        )
        assert resp.status_code == 200
        results = resp.json()["results"]
        assert len(results) == 2
        assert all(r["success"] for r in results)

    def test_bulk_status_update(self, client: TestClient):
        auth = _signup_and_login(client, "t_bulk_s@co.com", "BulkS Org")
        token = auth["access_token"]
        customer = _create_customer(client, token, "bulks_cust@test.com")

        t1 = _create_ticket(client, token, customer["id"], "BulkS T1")
        t2 = _create_ticket(client, token, customer["id"], "BulkS T2")

        resp = client.post(
            "/api/v1/tickets/bulk/status",
            json={"ticket_ids": [t1["id"], t2["id"]], "status": "OPEN"},
            headers=_auth(token),
        )
        assert resp.status_code == 200
        results = resp.json()["results"]
        assert all(r["success"] for r in results)
        assert all(r["new_status"] == "OPEN" for r in results)

    def test_bulk_invalid_transition_partial_failure(self, client: TestClient):
        """Bulk operations report failures per-ticket without aborting the batch."""
        auth = _signup_and_login(client, "t_bulk_f@co.com", "BulkF Org")
        token = auth["access_token"]
        customer = _create_customer(client, token, "bulkf_cust@test.com")

        t1 = _create_ticket(client, token, customer["id"], "Good ticket")
        t2 = _create_ticket(client, token, customer["id"], "Good ticket 2")
        # Move t2 to CANCELLED (terminal)
        client.post(
            f"/api/v1/tickets/{t2['id']}/status",
            json={"status": "CANCELLED"},
            headers=_auth(token),
        )

        # Try to bulk-move both to OPEN; t1 should succeed, t2 should fail
        resp = client.post(
            "/api/v1/tickets/bulk/status",
            json={"ticket_ids": [t1["id"], t2["id"]], "status": "OPEN"},
            headers=_auth(token),
        )
        if resp.status_code != 200:
            print("ERROR BODY:", resp.json())
        assert resp.status_code == 200
        results = resp.json()["results"]
        successes = [r for r in results if r["success"]]
        failures = [r for r in results if not r["success"]]
        assert len(successes) >= 1
        assert len(failures) >= 1
