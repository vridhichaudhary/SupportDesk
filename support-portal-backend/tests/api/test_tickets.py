def _signup_and_login(client: TestClient, email: str, org_name: str) -> dict:
    """Signup as OWNER and return {access_token, org_id, user_id}."""
    resp = client.post(
        "/api/v1/auth/signup",
        json={
            "organization_name": org_name,
            "industry": "Technology",
            "first_name": "Test",
            "last_name": "User",
            "email": email,
            "password": "Password123!",
        },
    )
    assert resp.status_code == 201, resp.text
    token = resp.json()["data"]["access_token"]

    # Fetch user profile to get org_id and user_id
    me_resp = client.get("/api/v1/auth/me", headers={"Authorization": f"Bearer {token}"})
    assert me_resp.status_code == 200, me_resp.text
    me = me_resp.json()["data"]
    return {
        "access_token": token,
        "org_id": me["organization_id"],
        "user_id": me["id"],
    }


def _auth(token: str) -> dict:
    return {"Authorization": f"Bearer {token}"}


def _create_customer(client: TestClient, token: str, email: str = "customer@test.com") -> dict:
    resp = client.post(
        "/api/v1/customers",
        json={"email": email, "name": "Test Customer"},
        headers=_auth(token),
    )
    assert resp.status_code == 201, resp.text
    return resp.json()


def _create_ticket(
    client: TestClient,
    token: str,
    customer_id: str,
    subject: str = "My first ticket",
) -> dict:
    resp = client.post(
        "/api/v1/tickets",
        json={
            "subject": subject,
            "body": "I need help with my order.",
            "customer_id": customer_id,
            "ticket_number": "",  # Will be auto-generated by API
        },
        headers=_auth(token),
    )
    assert resp.status_code == 201, resp.text
    return resp.json()


