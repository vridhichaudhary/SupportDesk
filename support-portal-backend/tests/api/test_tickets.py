class TestTicketLifecycle:
    def _setup(self, client: TestClient, email_prefix: str):
        auth = _signup_and_login(client, f"{email_prefix}@co.com", f"{email_prefix} Org")
        token = auth["access_token"]
        customer = _create_customer(client, token)
        ticket = _create_ticket(client, token, customer["id"])
        return token, ticket

    def test_assign_ticket(self, client: TestClient):
        token, ticket = self._setup(client, "t_assign")
        auth = _signup_and_login(client, "t_assign2@co.com", "t_assign2 Org")
        # Self-assign
        resp = client.post(
            f"/api/v1/tickets/{ticket['id']}/assign",
            json={"assigned_user_id": None, "assigned_team_id": None},
            headers=_auth(token),
        )
        assert resp.status_code == 200

    def test_assign_transitions_to_assigned(self, client: TestClient):
        auth = _signup_and_login(client, "t_trans@co.com", "Trans Org")
        token = auth["access_token"]
        customer = _create_customer(client, token, "trans_cust@test.com")
        ticket = _create_ticket(client, token, customer["id"])
        user_id = auth["user_id"]

        resp = client.post(
            f"/api/v1/tickets/{ticket['id']}/assign",
            json={"assigned_user_id": user_id},
            headers=_auth(token),
        )
        assert resp.status_code == 200
        assert resp.json()["status"] == "ASSIGNED"

    def test_reply_to_ticket(self, client: TestClient):
        token, ticket = self._setup(client, "t_reply")
        resp = client.post(
            f"/api/v1/tickets/{ticket['id']}/reply",
            json={"body": "We are looking into this.", "is_internal": False},
            headers=_auth(token),
        )
        assert resp.status_code == 200

    def test_internal_note(self, client: TestClient):
        token, ticket = self._setup(client, "t_note")
        resp = client.post(
            f"/api/v1/tickets/{ticket['id']}/reply",
            json={"body": "Internal only note.", "is_internal": True},
            headers=_auth(token),
        )
        assert resp.status_code == 200

    def test_get_thread_includes_notes(self, client: TestClient):
        token, ticket = self._setup(client, "t_thread")
        client.post(
            f"/api/v1/tickets/{ticket['id']}/reply",
            json={"body": "Agent reply", "is_internal": False},
            headers=_auth(token),
        )
        client.post(
            f"/api/v1/tickets/{ticket['id']}/reply",
            json={"body": "Internal note", "is_internal": True},
            headers=_auth(token),
        )
        resp = client.get(
            f"/api/v1/tickets/{ticket['id']}/thread?include_internal=true",
            headers=_auth(token),
        )
        assert resp.status_code == 200
        items = resp.json()
        # 3 items: original body + agent reply + internal note
        assert len(items) >= 2

    def test_get_thread_excludes_notes(self, client: TestClient):
        token, ticket = self._setup(client, "t_thread_excl")
        client.post(
            f"/api/v1/tickets/{ticket['id']}/reply",
            json={"body": "Internal only", "is_internal": True},
            headers=_auth(token),
        )
        resp = client.get(
            f"/api/v1/tickets/{ticket['id']}/thread?include_internal=false",
            headers=_auth(token),
        )
        assert resp.status_code == 200
        items = resp.json()
        # Internal notes should be excluded
        for item in items:
            assert item["thread_type"] != "INTERNAL_NOTE"


